export interface Product {
  drug_code: number
  din: string
  brand_name: string
  display_name: string
  company: string
  ai_group_no: string | null
  equivalence_key: string | null
  atc_number: string | null
  atc_name: string | null
  purpose?: string | null
  form: string | null
  route: string | null
  ingredient_label: string | null
  is_branded: number
  brand_rank: number
  brand_index?: number
  /**
   * A real per-unit price published by a Canadian government, or null.
   *
   * NULL FOR ~91% OF PRODUCTS, and that is correct rather than a gap to fill. See ADR-017: no
   * lawful, DIN-keyed Canadian retail price exists for any product in this catalogue, so the app
   * shows a price only where a government publishes one, and nothing at all where none does.
   *
   * There is deliberately no bare `price: number` field any more. The old `base_price` was
   * generated by a seeded PRNG for all 1,024 products and rendered with an "Est." prefix; the
   * prefix was load-bearing precisely because the number was invented.
   */
  benefit_price: BenefitPrice | null
  odb_ratio_pct: number | null
  odb_citation: string | null
}

/**
 * A per-unit amount a public drug plan reimburses a pharmacy. NOT a shelf price.
 *
 * `basis` is not optional and is not a tooltip. A payer price rendered as "$1.23" beside a
 * medicine is read as a shelf price by every user alive, so the basis ships in the same object as
 * the digits and the UI renders them in the same visual block.
 */
export interface BenefitPrice {
  din: string
  /** 'OBS' is a price a person read off a shelf tag — the only RETAIL price in the project. */
  jurisdiction: 'ON' | 'NS' | 'OBS'
  amountPerUnit: number
  /** "tablet", "capsule", "suppository", "mL", "g", "each" — makes "$X per ___" read correctly. */
  unit: string
  basis: string
  source: string
  /** ODB only, and only where the ministry reimburses less than the listed price. */
  ministryPays: number | null
  /** NS only — the interchangeable group the ceiling covers. It is not brand-specific. */
  interchangeableGroup: string | null
  /** Observed prices only: the pack the price was for, without which the number means nothing. */
  pack: { size: number; unit: string } | null
  /** Observed prices only: who saw it, where and when. */
  observed: { store: string; city: string; on: string; by: string; note?: string } | null
}

