export interface SearchFilters {
  healthCanadaListedOnly: boolean
  nameBrandOnly: boolean
  /**
   * Replaces the price-band filter and the sort-by-cost toggle.
   *
   * Both of those operated on a generated number. With real prices covering 92 of 1,024 products,
   * a "$10 – $20" band is meaningless — the real figures are per-unit reimbursement amounts
   * running from $0.0114 to $15.65, and 91% of products have none at all. Sorting a list by a
   * value that 91% of it does not have puts the unpriced majority in an arbitrary order and
   * implies the ordering means something.
   *
   * What a user can actually ask for is the one thing the data supports: show me only the ones
   * where somebody published a real number.
   */
  publishedPriceOnly: boolean
}

export const NO_FILTERS: SearchFilters = {
  healthCanadaListedOnly: false,
  nameBrandOnly: false,
  publishedPriceOnly: false,
}

/** A search result: the branded anchor, then everything equivalent to it. */
export interface ResultSet {
  query: string
  branded: Product | null
  alternatives: Product[]
  group: EqGroup | null
  /** Products that matched but belong to other equivalence groups. */
  otherMatches: Product[]
}
